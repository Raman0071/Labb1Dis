package org.example.dao;

import org.example.service.Passwords;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

/** Creates the lab schema and seed data, and opens a fresh connection per operation. */
public class Database {
    private final String url;
    public Database(String url) {
        this.url = url;
        try { Class.forName("org.h2.Driver"); }
        catch (ClassNotFoundException e) { throw new IllegalStateException("H2 JDBC driver missing", e); }
    }
    public Connection connect() throws SQLException { return DriverManager.getConnection(url, "sa", ""); }
    public void initialize() throws SQLException {
        try (Connection connection = connect(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(80) UNIQUE NOT NULL, password_hash VARCHAR(255) NOT NULL)");
            statement.execute("CREATE TABLE IF NOT EXISTS products (id BIGINT PRIMARY KEY, name VARCHAR(100) NOT NULL, description VARCHAR(500) NOT NULL, price DECIMAL(10,2) NOT NULL CHECK (price >= 0))");
            // Existing data is preserved when Tomcat restarts.
            statement.executeUpdate("INSERT INTO products SELECT 1, 'Anteckningsbok', 'En bok för idéer och föreläsningar.', 59.00 WHERE NOT EXISTS (SELECT 1 FROM products WHERE id = 1)");
            statement.executeUpdate("INSERT INTO products SELECT 2, 'Kaffemugg', 'En stadig mugg för långa labbpass.', 129.00 WHERE NOT EXISTS (SELECT 1 FROM products WHERE id = 2)");
            statement.executeUpdate("INSERT INTO products SELECT 3, 'Penna', 'En blå penna för nästa stora idé.', 19.50 WHERE NOT EXISTS (SELECT 1 FROM products WHERE id = 3)");
            try (var query = connection.prepareStatement("SELECT id FROM users WHERE username = ?")) {
                query.setString(1, "student");
                try (var result = query.executeQuery()) {
                    if (!result.next()) {
                        try (var insert = connection.prepareStatement("INSERT INTO users(username, password_hash) VALUES (?, ?)")) {
                            insert.setString(1, "student");
                            insert.setString(2, Passwords.hash("labb123"));
                            insert.executeUpdate();
                        }
                    }
                }
            }
        }
    }
}
